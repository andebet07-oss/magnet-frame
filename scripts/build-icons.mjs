// Fetches the artwork for src/icons/catalog.js:
//   - Material Symbols (Rounded) paths  → src/icons/symbolPaths.js
//   - Noto Emoji SVGs (Iconify "noto")  → public/icons/noto/<id>.svg
// Run with `npm run icons`. Needs network access (GitHub raw files and the npm registry).
// Nothing is added to package.json: the emoji package is downloaded with `npm pack` into a temp folder.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { EMOJI, SYMBOLS } from '../src/icons/catalog.js';

const SYMBOLS_BASE = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web';
const NOTO_PACKAGE = '@iconify-json/noto@1.2.10';

async function fetchSymbol({ id, file }) {
  const [folder, name] = file.split('/');
  const url = `${SYMBOLS_BASE}/${folder}/materialsymbolsrounded/${name}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${id}: ${res.status} ${url}`);
  const svg = await res.text();
  // Older files have no viewBox, only width/height (a 24×24 grid).
  const box = /viewBox="([^"]+)"/.exec(svg);
  const size = (attr) => Number(new RegExp(`\\s${attr}="([\\d.]+)"`).exec(svg)?.[1] ?? 24);
  const viewBox = box ? box[1].split(/\s+/).map(Number) : [0, 0, size('width'), size('height')];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`${id}: no path in ${url}`);
  return [id, { viewBox, path: paths.join(' ') }];
}

const symbols = Object.fromEntries(await Promise.all(SYMBOLS.map(fetchSymbol)));
writeFileSync(
  'src/icons/symbolPaths.js',
  `// Generated by scripts/build-icons.mjs from Google Material Symbols (Rounded), Apache License 2.0.\n` +
    `// Do not edit by hand: change src/icons/catalog.js and run \`npm run icons\`.\n` +
    `export const SYMBOL_PATHS = ${JSON.stringify(symbols, null, 2)};\n`,
);
console.warn(`symbols: ${Object.keys(symbols).length}`);

const temp = mkdtempSync(join(tmpdir(), 'noto-'));
try {
  execFileSync('npm', ['pack', NOTO_PACKAGE, '--silent'], { cwd: temp });
  execFileSync('tar', ['-xzf', `iconify-json-noto-${NOTO_PACKAGE.split('@').pop()}.tgz`], { cwd: temp });
  const set = JSON.parse(readFileSync(join(temp, 'package', 'icons.json'), 'utf8'));
  mkdirSync('public/icons/noto', { recursive: true });
  for (const { id } of EMOJI) {
    const icon = set.icons[id];
    if (!icon) throw new Error(`emoji "${id}" not in ${NOTO_PACKAGE}`);
    const width = icon.width ?? set.width ?? 128;
    const height = icon.height ?? set.height ?? 128;
    writeFileSync(
      `public/icons/noto/${id}.svg`,
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">${icon.body}</svg>\n`,
    );
  }
  console.warn(`emoji: ${EMOJI.length}`);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
