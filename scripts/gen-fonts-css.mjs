// Regenerates src/fonts/fonts.css from src/fonts/registry.js.
// Fails loudly if a weight/subset file is missing or a family name doesn't match the package.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { FONTS } from '../src/fonts/registry.js';

const lines = ['/* Generated by scripts/gen-fonts-css.mjs from src/fonts/registry.js. Do not edit by hand. */'];

for (const font of FONTS) {
  for (const weight of font.weights) {
    for (const subset of font.subsets) {
      const spec = `@fontsource/${font.pkg}/${subset}-${weight}.css`;
      const file = `node_modules/${spec}`;
      if (!existsSync(file)) throw new Error(`Missing ${spec}`);
      const css = readFileSync(file, 'utf8');
      if (!css.includes(`font-family: '${font.family}'`)) {
        throw new Error(`${spec} does not declare font-family '${font.family}'`);
      }
      lines.push(`@import "${spec}";`);
    }
  }
}

writeFileSync('src/fonts/fonts.css', `${lines.join('\n')}\n`);
console.warn(`fonts.css: ${lines.length - 1} imports for ${FONTS.length} families`);
